def fig3_gbm_paths():
    """Simulated geometric-Brownian-motion cost paths."""
    rng    = np.random.default_rng(42)
    n      = 200
    nsteps = 250
    t      = np.linspace(0.0, T, nsteps + 1)
    dt     = T / nsteps

    K  = 65.0
    Kp = adjusted_strike(K, FEES["Percentage"]["f"], FEES["Percentage"]["F"])

    # simulate paths
    paths = np.empty((n, nsteps + 1))
    paths[:, 0] = C0
    for i in range(n):
        Z = rng.standard_normal(nsteps)
        incr = (MU - 0.5 * SIGMA**2) * dt + SIGMA * np.sqrt(dt) * Z
        paths[i, 1:] = C0 * np.exp(np.cumsum(incr))

    breach = paths[:, -1] > Kp

    fig, ax = plt.subplots(figsize=(6.2, 4.8))

    for i in range(n):
        if breach[i]:
            ax.plot(t, paths[i], color="black", lw=0.5, alpha=0.55)
        else:
            ax.plot(t, paths[i], color="0.72", lw=0.5, alpha=0.7)

    ax.axhline(Kp, color="black", ls="--", lw=1.8,
               label=fr"$K'=\${Kp:.2f}$M (adjusted strike)")
    ax.axhline(C0, color="0.30", ls=":", lw=1.5, label=r"$C_0=\$50$M")

    ax.set_xlabel("Time  (years)")
    ax.set_ylabel(r"Project cost $C(t)$  (\$M)")
    ax.set_xlim(0, T)
    ax.legend(loc="upper left")
    ax.grid(alpha=0.30)

    pct = 100.0 * breach.mean()
    header(fig, r"Simulated GBM cost paths $C(t)$ "
                fr"($n=200$;  {pct:.0f}% breach $K'$ under % fee)")
    fig.tight_layout()
    save(fig, "fig2_gbm_paths.png")


