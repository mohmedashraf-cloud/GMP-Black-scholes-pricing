# 2.  CORE MODEL FUNCTIONS
# --------------------------------------------------------------------------
def adjusted_strike(K, f, F):
    """Equation (3): K' = (K - F) / (1 + f)."""
    return (K - F) / (1.0 + f)


def bs_call(C0, Kp, sigma, r, tau):
    """Bare Black-Scholes call value on the cost process (Eq. 9 inner term)."""
    d1 = (np.log(C0 / Kp) + (r + 0.5 * sigma**2) * tau) / (sigma * np.sqrt(tau))
    d2 = d1 - sigma * np.sqrt(tau)
    return C0 * norm.cdf(d1) - Kp * np.exp(-r * tau) * norm.cdf(d2)


def gmp_loss_premium(C0, Kp, sigma, r, tau, f):
    """Equation (9): GMP loss premium  V = (1 + f) * call(C0, K')."""
    return (1.0 + f) * bs_call(C0, Kp, sigma, r, tau)


def k_star(C0, sigma, r, T, z, f, F):
    """Equation (11): minimum acceptable GMP cap K*."""
    return (1.0 + f) * C0 * np.exp((r - 0.5 * sigma**2) * T
                                   + z * sigma * np.sqrt(T)) + F


def sigma_schedule(t, T):
    """Equation (13): stretched-exponential decline of cost volatility."""
    return SIG_MIN + (SIG0 - SIG_MIN) * np.exp(-LAMBDA * (t / T)**GAMMA)


def r_schedule(t, T):
    """Equation (14): phase-modulated risk-free rate."""
    return R0 - R1 * np.sin(np.pi * t / T) + R2 * (t / T)


def solve_pde(Kp, sigma_const, r_const, T,
              N=80, C_max=200.0, dtau=0.002,
              time_varying=False, store_every=20):
    """
    Explicit-Euler finite-difference solver for the Black-Scholes PDE
    (Eq. 12), posed in transformed time tau = T - t.

    Returns
    -------
    C     : cost grid, shape (N+1,)
    taus  : stored transformed-time values
    snaps : option-value snapshots, shape (len(taus), N+1)
    """
    dC = C_max / N
    C  = np.linspace(0.0, C_max, N + 1)
    V  = np.maximum(C - Kp, 0.0)                 # initial condition (tau = 0)

    nsteps = int(round(T / dtau))
    snaps, taus = [V.copy()], [0.0]

    for s in range(nsteps):
        tau = (s + 1) * dtau
        if time_varying:
            t_cal = T - tau                      # calendar time
            sig   = sigma_schedule(t_cal, T)
            rr    = r_schedule(t_cal, T)
        else:
            sig, rr = sigma_const, r_const

        # centred finite differences on the interior nodes
        d2V = (V[2:] - 2.0 * V[1:-1] + V[:-2]) / dC**2
        d1V = (V[2:] - V[:-2]) / (2.0 * dC)
        dVdtau = (0.5 * sig**2 * C[1:-1]**2 * d2V
                  + rr * C[1:-1] * d1V
                  - rr * V[1:-1])

        Vn = V.copy()
        Vn[1:-1] = V[1:-1] + dtau * dVdtau
        Vn[0]    = 0.0                                   # lower Dirichlet BC
        Vn[-1]   = C_max - Kp * np.exp(-rr * tau)        # upper Dirichlet BC
        V = Vn

        if (s + 1) % store_every == 0 or s == nsteps - 1:
            snaps.append(V.copy())
            taus.append(tau)

    return C, np.array(taus), np.array(snaps)


