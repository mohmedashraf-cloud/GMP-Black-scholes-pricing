# 1.  SHARED MODEL PARAMETERS  (Table 2 of the paper)
# --------------------------------------------------------------------------
C0    = 50.0      # base cost estimate, $M
T     = 2.5       # project duration, years
SIGMA = 0.18      # composite cost volatility (constant-parameter baseline)
MU    = 0.04      # expected real-world cost escalation rate
