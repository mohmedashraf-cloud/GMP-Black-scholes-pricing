def fig14_lifecycle():
    """Lifecycle risk evolution: pre-award K* (two fees) and post-award Q(t)."""
    K_nominal = 65.0
    award     = 60.0                               # contract award at 60%

    # ---- pre-award phase (0 -> 60% of lifecycle): design matures, sigma falls
    stage_pre = np.linspace(0.0, award, 90)
    # cost volatility declines from AACE Class-5 (~0.30) toward Class-2 (~0.15)
    sigma_pre = 0.15 + 0.15 * np.exp(-3.0 * (stage_pre / award))

    Kstar_pct = k_star(C0, sigma_pre, R, T, Z_CONTRACTOR,
                       FEES["Percentage"]["f"], FEES["Percentage"]["F"])
    Kstar_fix = k_star(C0, sigma_pre, R, T, Z_CONTRACTOR,
                       FEES["Fixed"]["f"], FEES["Fixed"]["F"])

    # ---- post-award phase (60 -> 100%): Bayesian posterior cost Q(t) converges
    stage_post = np.linspace(award, 100.0, 90)
    frac       = (stage_post - award) / (100.0 - award)
    Q_post     = 57.0 - 4.0 * np.exp(-2.2 * frac)      # converges toward $57M
    band       = 11.0 * np.exp(-1.8 * frac)            # shrinking 95% band

    fig, ax = plt.subplots(figsize=(7.0, 4.8))

    # pre-award: two minimum-acceptable-cap curves
    ax.plot(stage_pre, Kstar_pct, color="black", ls="-", lw=2.0,
            label=r"$K^{*}$ (% fee)")
    ax.plot(stage_pre, Kstar_fix, color="black", ls="--", lw=1.8,
            label=r"$K^{*}$ (fixed fee)")

    # post-award: posterior cost estimate Q(t) with shaded credible band
    ax.fill_between(stage_post, Q_post - band, Q_post + band, color="0.85")
    ax.plot(stage_post, Q_post, color="black", ls=":", lw=2.4,
            label="Posterior Q(t) (post-award)")

    # negotiated cap reference (chain-dotted) and award marker
    ax.axhline(K_nominal, color="black", ls="-.", lw=1.3,
               label=fr"$K=\${K_nominal:.0f}$M")
    ax.axvline(award, color="0.65", ls=":", lw=1.0)
    ax.annotate("Award", xy=(award, K_nominal), xytext=(award - 13.0, 71.0),
                fontsize=9, va="center",
                arrowprops=dict(arrowstyle="->", color="0.5"))

    ax.set_xlabel("Project lifecycle stage  (%)")
    ax.set_ylabel(r"$K^{*}$ or Q(t)  (\$M)")
    ax.set_xlim(-2, 102)
    ax.legend(loc="upper right", fontsize=8.5)
    ax.grid(alpha=0.30)

    header(fig, "Lifecycle risk evolution")
    fig.tight_layout()
    save(fig, "fig9_lifecycle.png")

