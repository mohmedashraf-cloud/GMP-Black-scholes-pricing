Z_CONTRACTOR = norm.ppf(1 - 0.10)     # z at alpha = 10%  -> 1.2816
Z_BANK       = norm.ppf(1 - 0.05)     # z at alpha =  5%  -> 1.6449

# time-varying schedule constants (Section 9.1)
SIG0, SIG_MIN, LAMBDA, GAMMA = 0.22, 0.12, 1.8, 1.2
R0, R1, R2                   = 0.10, 0.04, 0.01

