def fig11_validation():
    """Three-method validation: closed form, Monte Carlo, SD-PDE."""
    rng = np.random.default_rng(11)
    K   = 65.0
    f   = FEES["Percentage"]["f"]
    F   = FEES["Percentage"]["F"]
    Kp  = adjusted_strike(K, f, F)

    def mc_premium(sigma, r, T, n=20000):
        """Monte-Carlo estimate of the discounted GMP loss premium."""
        Z   = rng.standard_normal(n)
        CT  = C0 * np.exp((r - 0.5 * sigma**2) * T + sigma * np.sqrt(T) * Z)
        pay = (1.0 + f) * np.maximum(CT - Kp, 0.0)
        return np.exp(-r * T) * pay.mean()

    def pde_premium(sigma, r, T):
        """SD-PDE estimate of the GMP loss premium at (C0, T)."""
        C, _, snaps = solve_pde(Kp, sigma, r, T, N=80, C_max=200.0,
                                dtau=0.002, store_every=10**6)
        idx = int(round(C0 / (C[1] - C[0])))
        return (1.0 + f) * snaps[-1, idx]

    fig, axes = plt.subplots(1, 3, figsize=(12.0, 3.9))

    # ---- (a)  V vs sigma ----
    sig_line = np.linspace(0.08, 0.32, 120)
    V_line   = gmp_loss_premium(C0, Kp, sig_line, R, T, f)
    sig_pts  = np.array([0.10, 0.16, 0.22, 0.28])
    V_mc     = np.array([mc_premium(s, R, T)  for s in sig_pts])
    V_pde    = np.array([pde_premium(s, R, T) for s in sig_pts])

