# FIGURE 12  ->  fig7_bayesian.png
#   Corrections vs the previous version:
#     * 24 reporting periods (x-axis 0-25), matching the paper -- was 30.
#     * Observation noise removed from the synthetic Earned-Value series, so
#       the posterior mean and the breach probability P_k both come out as
#       the smooth, monotone curves shown in the paper -- the previous
#       version injected random noise that made panel (b) rise to ~70%
#       mid-project before falling, which is physically wrong.
# ==========================================================================
def fig12_bayesian():
    """Bayesian sequential updating of the cost posterior and breach prob."""
    n_period = 24                                  # monthly reporting periods
    months   = np.arange(0, n_period + 1)
    K        = 65.0
    f        = FEES["Percentage"]["f"]
    Kp       = adjusted_strike(K, f, FEES["Percentage"]["F"])

    # ground-truth cost-at-completion the project is really heading toward
    C_true = 57.0

    # Synthetic Earned-Value cost-at-completion estimates A_k = ACWP_k / CPI_k.
    # The estimate drifts smoothly from the base estimate C0 toward the true
    # final cost as the work proceeds.  No random noise is added: the Bayesian
    # filter is being illustrated, so the observation stream is the expected
    # (mean) EV signal and the posterior therefore evolves smoothly.
    cac = C_true - (C_true - C0) * np.exp(-months / 7.0)

    # prior on log-cost
    mu, var = np.log(C0), 0.07
    mu_hist          = [mu]
    lo_hist, hi_hist = [np.exp(mu - 1.96 * np.sqrt(var))], \
                       [np.exp(mu + 1.96 * np.sqrt(var))]

    # breach probability from the prior (period 0)
    P_hist = [1.0 - norm.cdf((np.log(Kp) - mu - (R - 0.5 * var) * T) /
                             (np.sqrt(var) * np.sqrt(T)))]

    for k in range(1, n_period + 1):
        # observation precision improves as the project matures: the EV
        # signal is noisier early (var_obs = 0.10) and sharper late (0.05)
        var_obs = 0.10 if k < n_period * 0.5 else 0.05
        alpha_k = np.log(cac[k])                  # expected log-cost signal

        # conjugate Gaussian update (Eqs. 19-20)
        var_new = 1.0 / (1.0 / var + 1.0 / var_obs)
        mu      = var_new * (mu / var + alpha_k / var_obs)
        var     = var_new

        mu_hist.append(mu)
        lo_hist.append(np.exp(mu - 1.96 * np.sqrt(var)))
        hi_hist.append(np.exp(mu + 1.96 * np.sqrt(var)))

        # breach probability against K' (Eq. 21)
        tau_k = max(T * (1.0 - k / n_period), 1e-6)
        z     = (np.log(Kp) - mu - (R - 0.5 * var) * tau_k) / \
                (np.sqrt(var) * np.sqrt(tau_k))
        P_hist.append(1.0 - norm.cdf(z))

    C_hat  = np.exp(np.array(mu_hist))
    P_hist = np.array(P_hist)

    fig, (axL, axR) = plt.subplots(1, 2, figsize=(11.0, 4.2))

    # (a) posterior cost evolution with 95% credible interval
    axL.fill_between(months, lo_hist, hi_hist, color="0.85",
                     label="95% credible interval")
    axL.plot(months, C_hat, color="black", lw=2.0,
             label=r"posterior mean $\hat{C}(k)$")
    axL.axhline(C_true, color="black", ls="--", lw=1.6,
                label=fr"true $C(T)=\${C_true:.0f}$M")
    axL.axhline(Kp, color="black", ls=":", lw=1.6,
                label=fr"$K'=\${Kp:.1f}$M")
    axL.set_title("(a)  Posterior cost evolution", fontsize=10)
    axL.set_xlabel("Reporting period $k$")
    axL.set_ylabel(r"Cost estimate  (\$M)")
    axL.set_xlim(0, n_period + 1)
    axL.legend(loc="upper right", fontsize=8.5)
    axL.grid(alpha=0.30)

    # (b) GMP breach probability -- smooth monotone decline
    axR.plot(months, 100.0 * P_hist, color="black", lw=2.0,
             label=r"$P(C(T)>K')$")
    axR.axhline(10.0, color="black", ls="--", lw=1.5,
                label="10% alert threshold")
    axR.set_title(r"(b)  GMP breach probability $P(C(T)>K')$", fontsize=10)
    axR.set_xlabel("Reporting period $k$")
    axR.set_ylabel(r"$P(C(T)>K')$  (%)")
    axR.set_xlim(0, n_period + 1)
    axR.set_ylim(0, 80)
    axR.legend(loc="upper right", fontsize=8.5)
    axR.grid(alpha=0.30)

    header(fig, "Bayesian sequential updating across 24 monthly "
                "reporting periods")
    fig.tight_layout()
    save(fig, "fig7_bayesian.png")


